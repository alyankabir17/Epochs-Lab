test('theme follows system preference and persists a manual selection', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.evaluate(() => localStorage.removeItem('epochs_theme'))
  await page.reload()
  await expect.poll(() => page.evaluate(() => document.documentElement.classList.contains('dark'))).toBe(true)
  const landingToggle = page.getByRole('button', { name: 'Switch to light mode' })
  await expect(landingToggle).toBeVisible()
  await landingToggle.click()
  await expect.poll(() => page.evaluate(() => localStorage.getItem('epochs_theme'))).toBe('light')
  await expect.poll(() => page.evaluate(() => document.documentElement.classList.contains('dark'))).toBe(false)
  await page.getByRole('button', { name: 'Switch to dark mode' }).click()
  await expect.poll(() => page.evaluate(() => localStorage.getItem('epochs_theme'))).toBe('dark')
  await page.reload()
  await expect.poll(() => page.evaluate(() => document.documentElement.classList.contains('dark'))).toBe(true)
  await page.getByRole('link', { name: 'Start a project', exact: true }).first().click()
  await expect(page.getByRole('button', { name: /Switch to .* mode/ })).toHaveCount(0)
})

