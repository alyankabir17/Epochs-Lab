test('desktop sidebar resizes, clamps, collapses, and persists its state', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.evaluate(() => {
    localStorage.removeItem('epochs_dashboard_sidebar_width')
    localStorage.removeItem('epochs_dashboard_sidebar_collapsed')
  })
  await page.reload()
  await page.getByRole('link', { name: 'Start a project', exact: true }).first().click()

  const sidebar = page.locator('.dashboard-sidebar')
  const handle = page.locator('.dashboard-sidebar-resize-handle')
  await expect(handle).toBeVisible()
  const initialWidth = await sidebar.evaluate((element) => element.getBoundingClientRect().width)
  const box = await handle.boundingBox()
  await page.mouse.move(box.x + box.width / 2, box.y + 100)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2 + 50, box.y + 100)
  await page.mouse.up()
  await expect.poll(() => sidebar.evaluate((element) => element.getBoundingClientRect().width)).toBeGreaterThan(initialWidth + 40)
  const savedWidth = await page.evaluate(() => Number(localStorage.getItem('epochs_dashboard_sidebar_width')))
  expect(savedWidth).toBeGreaterThan(296)
  expect(savedWidth).toBeLessThanOrEqual(340)

  await page.reload()
  await page.getByRole('link', { name: 'Start a project', exact: true }).first().click()
  await expect.poll(() => sidebar.evaluate((element) => element.getBoundingClientRect().width)).toBe(savedWidth)
  await page.getByRole('button', { name: 'Collapse sidebar' }).click()
  await expect(page.getByRole('button', { name: 'Expand sidebar' })).toBeVisible()
  await expect.poll(() => sidebar.evaluate((element) => Math.round(element.getBoundingClientRect().width))).toBe(72)
  await expect(page.getByRole('link', { name: 'All projects' })).toBeVisible()
  await expect(page.getByText('All projects', { exact: true })).toBeHidden()

  await page.reload()
  await page.getByRole('link', { name: 'Start a project', exact: true }).first().click()
  await expect(page.getByRole('button', { name: 'Expand sidebar' })).toBeVisible()
  await expect.poll(() => sidebar.evaluate((element) => Math.round(element.getBoundingClientRect().width))).toBe(72)
})

